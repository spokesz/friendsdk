#!/usr/bin/env node
// Usage: node scripts/sync-contract-abi.mjs [--check]
// Reads the local contracts/ Forge build; never compiles or deploys.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256 } from "viem";

const sdkRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
if (args.some((arg) => arg !== "--check")) {
  throw new Error("Usage: node scripts/sync-contract-abi.mjs [--check]");
}
const project = path.join(sdkRoot, "contracts");
const artifactPath = path.join(project, "out/ChanceGame.sol/ChanceGame.json");
const outputPath = path.join(sdkRoot, "src/chance-game-abi.ts");
const sourceName = "src/ChanceGame.sol";
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const sorted = (value) => Array.isArray(value)
  ? value.map(sorted)
  : value !== null && typeof value === "object"
    ? Object.fromEntries(Object.keys(value).sort().map((key) => [key, sorted(value[key])]))
    : value;
const canonical = (value) => JSON.stringify(sorted(value));
// Forge omits empty inputs/outputs that the compiler's own metadata ABI spells out, on
// receive above all. Default both sides so the guard catches real differences only.
const canonicalAbi = (value) => Array.isArray(value)
  ? JSON.stringify(value.map((entry) => canonical(entry.type === "function"
      ? { ...entry, inputs: entry.inputs ?? [], outputs: entry.outputs ?? [] }
      : { ...entry, inputs: entry.inputs ?? [] })).sort())
  : null;

let artifact;
try {
  artifact = JSON.parse(await readFile(artifactPath, "utf8"));
} catch (error) {
  throw new Error(`Cannot read ${artifactPath}. Run npm run build:contracts first.`, { cause: error });
}
const metadata = artifact.metadata ?? JSON.parse(artifact.rawMetadata);
if (
  !Array.isArray(artifact.abi)
  || metadata.settings?.compilationTarget?.[sourceName] !== "ChanceGame"
  || !metadata.sources?.[sourceName]
  || !metadata.compiler?.version
  || canonicalAbi(artifact.abi) !== canonicalAbi(metadata.output?.abi)
) {
  throw new Error("Artifact is not a complete, consistent ChanceGame Forge build.");
}

// Verify every imported source against the compiler's own hashes, not just ChanceGame.sol.
// A stale artifact must fail rather than labeling an old ABI with a newer source fingerprint.
const sourceHashes = [];
for (const name of Object.keys(metadata.sources).sort()) {
  const source = await readFile(path.resolve(project, name));
  if (keccak256(source) !== metadata.sources[name].keccak256) {
    throw new Error(`Stale Forge artifact: ${name} differs from its compiled source. Rebuild explicitly before syncing.`);
  }
  sourceHashes.push({ source: name, sha256: sha256(source) });
}

const provenance = {
  source: `contracts/${sourceName}`,
  sourceSha256: sourceHashes.find((entry) => entry.source === sourceName).sha256,
  sourceKeccak256: metadata.sources[sourceName].keccak256,
  compiledSourcesSha256: sha256(canonical(sourceHashes)),
  abiSha256: sha256(canonical(artifact.abi)),
  compiler: metadata.compiler.version,
  compilerSettings: metadata.settings,
};
const generated = `// Generated by scripts/sync-contract-abi.mjs from the local Forge artifact.
// Source of truth: contracts/src/ChanceGame.sol.
// All imported source hashes are verified against the build.
// Regenerate after an explicit contract build; --check verifies the same output without writing.

export const CHANCE_GAME_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const;

export const CHANCE_GAME_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

if (check) {
  let current;
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    throw new Error("src/chance-game-abi.ts is missing. Run sync-contract-abi.mjs to generate it.");
  }
  if (current !== generated) {
    throw new Error("src/chance-game-abi.ts differs from the verified contract build. Run sync-contract-abi.mjs to update it.");
  }
  console.log("ChanceGame ABI and source provenance match the verified Forge build.");
} else {
  await writeFile(outputPath, generated);
  console.log("Generated src/chance-game-abi.ts from the verified Forge build.");
}
